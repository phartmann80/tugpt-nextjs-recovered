-- ---------------------------------------------------------------------------
-- 10. Close the direct-write hole
-- ---------------------------------------------------------------------------

-- This is the load-bearing statement of the migration. Everything above is
-- only enforcement if the table cannot be written around it.
REVOKE INSERT, UPDATE, DELETE ON public.organization_invitations FROM authenticated;

-- `anon` held SELECT on this table. The row policy requires
-- `auth.role() = 'authenticated'`, so it returned nothing and the grant was
-- inert — but a grant that only a policy makes safe is one policy edit away
-- from being a leak of every pending invitation's address, role and issuer.
-- An unauthenticated caller has no reason to read invitations: accepting one
-- requires a session, so the invitee signs in first and arrives as
-- `authenticated`.
REVOKE ALL ON public.organization_invitations FROM anon;

-- The policies are dropped too. A policy that permits a write for which no
-- grant exists is dead code that reads like live authorization, and the next
-- person to restore a grant would silently restore the hole with it.
DROP POLICY IF EXISTS "Owners and Admins can create invitations" ON public.organization_invitations;
DROP POLICY IF EXISTS "Owners and Admins can update invitations" ON public.organization_invitations;

-- SELECT stays: an admin listing pending invitations is legitimate, and the
-- existing SELECT policy already scopes rows to the caller's organization.
-- Note what that policy does NOT permit: the invitee cannot read their own
-- invitation before they are a member. That is intentional — they do not need
-- to, because they hold the token, and `accept_invitation` is the only thing
-- that needs to resolve it.

GRANT EXECUTE ON FUNCTION public.create_invitation(UUID, TEXT, public.organization_role) TO authenticated;
GRANT EXECUTE ON FUNCTION public.revoke_invitation(UUID) TO authenticated;
GRANT EXECUTE ON FUNCTION public.accept_invitation(TEXT) TO authenticated;

REVOKE ALL ON FUNCTION private.create_invitation(UUID, TEXT, public.organization_role) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION private.revoke_invitation(UUID) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION private.accept_invitation(TEXT) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION private.hash_invitation_token(TEXT) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION private.new_invitation_token() FROM PUBLIC, anon, authenticated;
